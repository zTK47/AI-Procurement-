"""Benchmark the LiteLLM gateway models on ProcAI's parsing task.

Every model gets the same prompts through the production parser
(LiteLLMParser). Reports correctness, tokens, latency and cost per request
(prices from the gateway's /model/info) and writes docs/MODEL-EVALUATION.md.

Usage: .venv/bin/python scripts/benchmark_models.py [model ...]
Needs LITELLM_API_BASE and LITELLM_API_KEY (e.g. from .env).
"""

import os
import sys
import time
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import httpx  # noqa: E402
import litellm  # noqa: E402
from dotenv import load_dotenv  # noqa: E402

from app.infrastructure.llm_client import LiteLLMSettings, complete  # noqa: E402
from app.infrastructure.parsers import LiteLLMParser  # noqa: E402
from app.infrastructure.seed import CATALOG_ITEMS  # noqa: E402

CASES = [
    ("I need 5 new Lenovo Laptop", 5, "lenovo"),
    ("Bitte bestelle 3 Bürostühle", 3, "chair"),
    ("could you get us two of those logitech mice?", 2, "mouse"),
    ("Please order three monitors for the team", 3, "monitor"),
    ("10x Logitech MX Keys", 10, "keys"),
]
OUTPUT = ROOT / "docs" / "MODEL-EVALUATION.md"


def gateway_models(base: str, key: str) -> tuple[list[str], dict[str, tuple[float, float]]]:
    headers = {"Authorization": f"Bearer {key}"}
    info = httpx.get(base.removesuffix("/v1") + "/model/info", headers=headers, timeout=30).json()["data"]
    prices = {
        m["model_name"]: (m["model_info"].get("input_cost_per_token") or 0.0,
                          m["model_info"].get("output_cost_per_token") or 0.0)
        for m in info
    }
    return sorted(prices), prices


def run(model: str, base: str, key: str, price: tuple[float, float], categories: list[str]) -> dict:
    settings = LiteLLMSettings(base, key, model)
    correct, tokens_in, tokens_out, seconds, errors = 0, 0, 0, 0.0, []
    for text, quantity, keyword in CASES:
        usage = {}

        def call(messages, **kwargs):
            response = complete(messages, settings=settings, **kwargs)
            usage["value"] = response.usage
            return response

        started = time.perf_counter()
        try:
            parsed = LiteLLMParser(categories, complete=call).parse(text)
            correct += parsed.quantity == quantity and keyword in parsed.product_name.lower()
        except Exception as error:  # a failing model is a result, not a crash
            errors.append(type(error).__name__)
        seconds += time.perf_counter() - started
        if "value" in usage:
            tokens_in += usage["value"].prompt_tokens
            tokens_out += usage["value"].completion_tokens
    n = len(CASES)
    return {
        "model": model,
        "correct": correct,
        "tokens_in": tokens_in / n,
        "tokens_out": tokens_out / n,
        "seconds": seconds / n,
        "cost": (tokens_in * price[0] + tokens_out * price[1]) / n,
        "priced": any(price),
        "error": errors[0] if errors else "",
    }


def main() -> None:
    load_dotenv(ROOT / ".env")
    litellm.suppress_debug_info = True
    base, key = os.environ["LITELLM_API_BASE"].rstrip("/"), os.environ["LITELLM_API_KEY"]
    available, prices = gateway_models(base, key)
    models = sys.argv[1:] or available
    categories = sorted({item[2] for item in CATALOG_ITEMS})

    results = []
    for model in models:
        result = run(model, base, key, prices.get(model, (0.0, 0.0)), categories)
        results.append(result)
        print(f"{model:30} {result['correct']}/{len(CASES)}  {result['seconds']:5.1f}s  ${result['cost']:.6f}")

    results.sort(key=lambda r: (-r["correct"], r["cost"] if r["priced"] else 1, r["seconds"]))
    lines = [
        "# Model evaluation",
        "",
        f"Generated by `scripts/benchmark_models.py` on {date.today().isoformat()} against the LiteLLM gateway.",
        f"Task: ProcAI prompt parsing ({len(CASES)} prompts: English, German, colloquial, number words, \"10x\").",
        "A prompt counts as correct when quantity and product match. Values are averages per request.",
        "",
        "| Model | Correct | Tokens in | Tokens out | Seconds | USD per request | Note |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in results:
        cost = f"{r['cost']:.6f}" if r["priced"] else "no price listed"
        note = f"error: {r['error']}" if r["error"] and r["correct"] == 0 else ""
        lines.append(f"| `{r['model']}` | {r['correct']}/{len(CASES)} | {r['tokens_in']:.0f} | {r['tokens_out']:.0f} "
                     f"| {r['seconds']:.1f} | {cost} | {note} |")
    lines += ["", "Prompts:", ""] + [f"- \"{text}\" → {quantity} × {keyword}" for text, quantity, keyword in CASES]
    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
